#!/usr/bin/env python3
"""Deterministic release-to-release provenance probe over the fetched
ESP-IDF supplicant sources in lab/ (v44_wpa.c, v52_wpa.c, ... and the
*_sae.c files, refetched with `make sources-esp`). For each release
snapshot and each upstream guard marker (verbatim strings from the
official hostap files under report/snippets/upstream/), report present
with line number, or absent. Markers and files are pinned below; the
comparison anchors are the official 2.3 and current w1.fi wpa.c.
Writes lab/esp_guard_probe.md."""
import os, re, sys, argparse

HERE = os.path.dirname(os.path.abspath(__file__))

# marker -> regex (plain strings, no regex metacharacters in the markers
# we chose, so re.escape keeps the search literal)
WPA_MARKERS = [
    ("ptk-guard", r"Do not re-install same PTK"),
    ("gtk-guard-comment", r"Detect possible key reinstallation"),
    ("gtk-guard-string", r"already in-use GTK"),
]
SAE_MARKERS = [
    ("reflection-guard", r"evidence of a reflection attack"),
]
ALL_MARKERS = WPA_MARKERS + SAE_MARKERS

# (label, fetched files under lab/); tags absent from lab/ yield no rows
SNAPSHOTS = [
    ("wpa_supplicant 2.3 (w1.fi, pinned tarball)", ["official_wpa_2.3_wpa.c"]),
    ("wpa_supplicant 2.6 (w1.fi, pinned tarball)", ["official_wpa_2.6_wpa.c", "official_sae_2.6.c"]),
    ("ESP-IDF v4.4", ["v44_wpa.c", "v44_sae.c"]),
    ("ESP-IDF v5.2", ["v52_wpa.c"]),
]

def probe(path, markers):
    lab = os.path.join(HERE, os.pardir, "lab")
    p = os.path.join(lab, path)
    if not os.path.exists(p):
        return None
    text = open(p, encoding="utf-8", errors="replace").read().splitlines()
    out = []
    for name, needle in markers:
        pat = re.compile(re.escape(needle))
        hits = [i for i, line in enumerate(text, 1) if pat.search(line)]
        out.append((name, needle, hits))
    return out

def fmt(rows_):
    if rows_ is None:
        return "(file not fetched for this snapshot)"
    return "; ".join("%s: %s%s" % (n, ("line " + ",".join(map(str, h))) if h else "absent",
                                   "") for n, _, h in rows_)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, os.pardir, "lab",
                                                  "esp_guard_probe.md"))
    a = ap.parse_args()
    lines = [
        "# KRACK/SAE guard probe across release snapshots",
        "",
        "Generated by `tools/esp_guard_probe.py` over `lab/` sources",
        "(refetch with `make sources-esp`). Markers are verbatim strings",
        "from the official upstream files; a hit prints the line number",
        "in the probed file, otherwise `absent`. Every marker is checked",
        "in every fetched file of every snapshot, so a hit that lives in",
        "another file is visible, not assumed.",
        "",
    ]
    for label, files in SNAPSHOTS:
        lines.append("## %s" % label)
        lines.append("")
        rows = []
        for fname in files:
            for mname, marker in ALL_MARKERS:
                res = probe(fname, [(mname, marker)])
                if res is None:
                    continue
                hits = res[0][2]
                rows.append("`%s`: %s" % (mname,
                                          "line " + ", ".join(map(str, hits))
                                          if hits else "absent"))
        if rows:
            lines.append("- " + "; ".join(rows))
        else:
            lines.append("- (no fetched source for this snapshot in `lab/`)")
        lines.append("")
    text = "\n".join(lines) + "\n"
    open(a.out, "w").write(text)
    sys.stdout.write(text)

if __name__ == "__main__":
    main()
